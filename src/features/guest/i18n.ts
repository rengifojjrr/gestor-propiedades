/**
 * Textos ES/EN de la app del huésped y de lo que comparte con el inquilino (chat y reportes).
 * Uso: const t = makeT(GUEST, lang); t('hello', { name }).
 */
import type { AccessCodeView, Incident, Lang, MaintenanceCategory } from '@/domain/types';
import { translate, type Dict } from '@/lib/i18n';

export function makeT<K extends string>(dict: Dict<K>, lang: Lang) {
  return (key: K, vars?: Record<string, string | number>) => translate(dict, lang, key, vars);
}

/** Plural sencillo: elige la clave «_one» o «_other». */
export function plural(n: number, one: string, other: string): string {
  return n === 1 ? one : other;
}

